#!/usr/bin/env python3
"""Generate packages/db/migrations/0031_food_usda.sql from the USDA FoodData Central SR Legacy CSV release.

Usage: python3 -I build-seed.py <dir with food.csv, food_nutrient.csv, food_portion.csv> <out.sql>
Source: https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_csv_2018-04.zip (public domain, CC0),
downloaded 2026-11-08, sha256 b80817294b8850530aaedf2e515c02593b1824f763a0ff356e5c2081643e6fd0.
Only foods listed in foods-pr.json are emitted. Every number comes from the USDA files; nothing is typed by hand.
"""
import csv
import json
import os
import sys

SRC, OUT = sys.argv[1], sys.argv[2]
HERE = os.path.dirname(os.path.abspath(__file__))
CUR = json.load(open(os.path.join(HERE, "foods-pr.json"), encoding="utf-8"))["foods"]
WANT = {str(f[0]): f for f in CUR}
NUTRIENTS = {"1008": "kcal", "1003": "protein_g", "1005": "carb_g", "1004": "fat_g", "1079": "fiber_g",
             "2000": "sugar_g", "1093": "sodium_mg", "1258": "sat_fat_g"}

food = {r["fdc_id"]: r for r in csv.DictReader(open(os.path.join(SRC, "food.csv"))) if r["fdc_id"] in WANT}
missing = sorted(set(WANT) - set(food))
if missing:
    sys.exit(f"not in USDA file: {missing}")
vals = {k: {} for k in WANT}
for r in csv.DictReader(open(os.path.join(SRC, "food_nutrient.csv"))):
    if r["fdc_id"] in WANT and r["nutrient_id"] in NUTRIENTS:
        vals[r["fdc_id"]][NUTRIENTS[r["nutrient_id"]]] = float(r["amount"])
portions = {k: [] for k in WANT}
for r in csv.DictReader(open(os.path.join(SRC, "food_portion.csv"))):
    if r["fdc_id"] in WANT and r["gram_weight"]:
        portions[r["fdc_id"]].append(r)

ES = [("tablespoon", "cucharada"), ("tbsp", "cucharada"), ("teaspoon", "cucharadita"), ("tsp", "cucharadita"),
      ("cup", "taza"), ("slice", "rebanada"), ("extra large", "extra grande"), ("extra small", "extra pequeño"),
      ("medium", "mediano"), ("large", "grande"), ("small", "pequeño"), ("oz", "onza"), ("fl", "fluida"),
      ("NLEA serving", "porción NLEA"), ("serving", "porción"), ("breast", "pechuga"), ("thigh", "muslo"),
      ("drumstick", "pierna"), ("piece", "pedazo"), ("fruit", "unidad"), ("cracker", "galleta"),
      ("tortilla", "tortilla"), ("roll", "pan"), ("chopped", "picado"), ("diced", "en cubitos"),
      ("sliced", "en rebanadas"), ("mashed", "majado"), ("whole", "entero"), ("pieces", "pedazos"),
      ("unit", "unidad"), ("stick", "barra"), ("pat", "porción")]


def es(text: str) -> str:
    out = text
    for en, sp in ES:
        out = out.replace(en, sp)
    return out


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def n(v):
    return "NULL" if v is None else repr(round(v, 3))


lines = [
    "-- GENERATED by packages/db/usda/build-seed.py from USDA FoodData Central SR Legacy (2018-04, CC0).",
    "-- Do not edit by hand: change foods-pr.json and regenerate. Values per 100 g of edible portion.",
    "ALTER TABLE app.food NO FORCE ROW LEVEL SECURITY;",
    "ALTER TABLE app.food_portion NO FORCE ROW LEVEL SECURITY;",
    "INSERT INTO app.food (fdc_id, source, source_release, name_es, name_usda, food_group, allergens, diet_tags,",
    "  kcal, protein_g, carb_g, fat_g, fiber_g, sugar_g, sodium_mg, sat_fat_g) VALUES",
]
rows = []
# Diet tags follow from allergens too: a food with milk is "lacteo" for a member who excludes dairy, egg is "huevo",
# fish and shellfish likewise. Without this a vegan could receive bread made with milk or egg.
ALLERGEN_TAG = {"leche": "lacteo", "huevo": "huevo", "pescado": "pescado", "marisco": "marisco"}
for fid, (fdc, name_es, group, allergens, tags) in sorted(WANT.items(), key=lambda kv: kv[1][1]):
    tags = sorted(set(tags) | {ALLERGEN_TAG[a] for a in allergens if a in ALLERGEN_TAG})
    v = vals[fid]
    for need in ("kcal", "protein_g", "carb_g", "fat_g"):
        if need not in v:
            sys.exit(f"{fid} {food[fid]['description']}: missing {need}")
    arr = lambda xs: "ARRAY[" + ",".join(q(x) for x in xs) + "]::text[]" if xs else "'{}'::text[]"
    rows.append(f"  ({fid}, 'usda_fdc', 'sr_legacy_2018-04', {q(name_es)}, {q(food[fid]['description'])}, {q(group)}, "
                f"{arr(allergens)}, {arr(tags)}, {n(v['kcal'])}, {n(v['protein_g'])}, {n(v['carb_g'])}, "
                f"{n(v['fat_g'])}, {n(v.get('fiber_g'))}, {n(v.get('sugar_g'))}, {n(v.get('sodium_mg'))}, "
                f"{n(v.get('sat_fat_g'))})")
lines.append(",\n".join(rows))
lines.append("ON CONFLICT (fdc_id) DO NOTHING;")
lines.append("")
lines.append("INSERT INTO app.food_portion (fdc_id, seq, amount, label_usda, label_es, gram_weight) VALUES")
prow = []
for fid in sorted(WANT):
    for r in sorted(portions[fid], key=lambda r: int(r["seq_num"] or 0)):
        amt = float(r["amount"] or 1)
        lab = (r["modifier"] or r["portion_description"] or "porción").strip()
        prow.append(f"  ({fid}, {int(r['seq_num'] or 0)}, {n(amt)}, {q(lab)}, {q(es(lab))}, {n(float(r['gram_weight']))})")
lines.append(",\n".join(prow))
lines.append("ON CONFLICT (fdc_id, seq) DO NOTHING;")
lines.append("ALTER TABLE app.food FORCE ROW LEVEL SECURITY;")
lines.append("ALTER TABLE app.food_portion FORCE ROW LEVEL SECURITY;")
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{len(rows)} foods, {len(prow)} portions -> {OUT}")
