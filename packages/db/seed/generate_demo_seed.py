"""Generate packages/db/seed/demo.sql (synthetic DEMO data). UUIDs must match packages/shared/src/demo.ts.

Run: python3 packages/db/seed/generate_demo_seed.py
"""
from pathlib import Path

A, B = "a", "b"
def u(org, n):  # fixed, readable UUIDs
    return f"{org}0000000-0000-4000-8000-{n:012d}"

ORG = {A: ("Demo Gym Norte", "pro"), B: ("Demo Club Sur", "esencial")}
LOCS = {A: [(11, "Demo Sede San Juan", "San Juan"), (12, "Demo Sede Bayamón", "Bayamón")],
        B: [(11, "Demo Sede Ponce", "Ponce")]}
STAFF = {  # person n, role, display name, location ns
    A: [(101, "owner", "Carmen Ortiz", []), (102, "location_manager", "Luis Vega", [11]),
        (103, "front_desk", "Marisol Cruz", [11]), (104, "front_desk", "Javier Colón", [12]),
        (105, "trainer", "Ricardo Santos", [11]), (106, "accountant", "Elena Pagán", [])],
    B: [(101, "owner", "Héctor Ramos", []), (103, "front_desk", "Nilda Torres", [11])],
}
MEMBERS = {  # person n, full name, location n, status
    A: [(110, "Ana Rivera Demo", 11, "active"), (111, "Pedro Morales Demo", 11, "active"),
        (112, "Sofía Delgado Demo", 11, "trial"), (113, "Miguel Ayala Demo", 11, "past_due"),
        (114, "Lucía Font Demo", 11, "frozen"), (115, "José Marrero Demo", 12, "active"),
        (116, "Gabriela Soto Demo", 12, "lead"), (117, "Andrés Vélez Demo", 12, "active"),
        (130, "Diego Méndez Demo", 11, "active")],  # 130 is the guardian's ward (minor)
    B: [(110, "Isabel Rosario Demo", 11, "active"), (111, "Tomás Ocasio Demo", 11, "trial")],
}
GUARDIAN = (120, 130)  # Rosa Méndez (person 120, org A) → ward member person 130
CONSENTS = {  # (member person n, channel, purpose)
    A: [(110, "sms", "reminder"), (110, "email", "transactional"), (110, "whatsapp", "marketing"),
        (111, "sms", "reminder"), (113, "email", "transactional"), (115, "sms", "reminder")],
    B: [(110, "sms", "reminder")],
}
INBOUND = {A: [(11, "sms", "+17875550101", "Hola, quiero saber el horario del sábado"),
               (12, "whatsapp", "+17875550102", "BAJA")],
           B: [(11, "sms", "+17875550201", "¿Tienen clases de spinning?")]}

def q(s):
    return "'" + s.replace("'", "''") + "'"

tables = ["organization", "legal_entity", "brand", "location", "person", "member", "staff_member",
          "staff_location", "guardian_link", "consent", "consent_event", "message_policy", "inbound_message"]
out = ["-- DEMO seed — synthetic data only (generated by generate_demo_seed.py; do not edit by hand).",
       "-- Runs as the schema owner. FORCE RLS is lifted only for the duration of the seed and restored at the end.",
       "-- Idempotent: does nothing if the demo organisation already exists."]
out.append("DO $seed$ BEGIN")
out.append(f"IF EXISTS (SELECT 1 FROM app.organization WHERE id = {q(u(A, 1))}) THEN RETURN; END IF;")
out += [f"ALTER TABLE app.{t} NO FORCE ROW LEVEL SECURITY;" for t in tables]
for org in (A, B):
    name, plan = ORG[org]
    out.append(f"INSERT INTO app.organization (id, name, saas_plan) VALUES ({q(u(org,1))}, {q(name)}, {q(plan)});")
    out.append(f"INSERT INTO app.legal_entity (id, org_id, legal_name) VALUES ({q(u(org,2))}, {q(u(org,1))}, {q(name + ' LLC')});")
    out.append(f"INSERT INTO app.brand (id, org_id, legal_entity_id, name, theme) VALUES ({q(u(org,3))}, {q(u(org,1))}, {q(u(org,2))}, {q(name.replace('Gym', 'Fitness') if org == A else name)}, '{{}}');")
    out.append(f"INSERT INTO app.message_policy (org_id, window_start, window_end) VALUES ({q(u(org,1))}, '08:00', '21:00');")
    for n, lname, muni in LOCS[org]:
        out.append(f"INSERT INTO app.location (id, org_id, brand_id, legal_entity_id, name, municipality) VALUES ({q(u(org,n))}, {q(u(org,1))}, {q(u(org,3))}, {q(u(org,2))}, {q(lname)}, {q(muni)});")
    for n, role, dname, locs in STAFF[org]:
        email = f"{role}.{n}.seed.{org}@demo.invalid"
        out.append(f"INSERT INTO app.person (id, email) VALUES ({q(u(org,n))}, {q(email)});")
        out.append(f"INSERT INTO app.staff_member (id, org_id, person_id, role, display_name) VALUES ({q(u(org,n+400))}, {q(u(org,1))}, {q(u(org,n))}, {q(role)}, {q(dname)});")
        for ln in locs:
            out.append(f"INSERT INTO app.staff_location (org_id, staff_member_id, location_id) VALUES ({q(u(org,1))}, {q(u(org,n+400))}, {q(u(org,ln))});")
    for n, fname, ln, status in MEMBERS[org]:
        email = f"{fname.split()[0].lower().replace('í','i').replace('é','e').replace('á','a').replace('ó','o').replace('ú','u')}.{n}.{org}@demo.invalid"
        out.append(f"INSERT INTO app.person (id, email) VALUES ({q(u(org,n))}, {q(email)});")
        out.append(f"INSERT INTO app.member (id, org_id, person_id, home_location_id, full_name, status, member_no) VALUES ({q(u(org,n+100))}, {q(u(org,1))}, {q(u(org,n))}, {q(u(org,ln))}, {q(fname)}, {q(status)}, {q(f'{org.upper()}-{n:04d}')});")
    for n, ch, purpose in CONSENTS[org]:
        cid = u(org, 900 + len([1 for line in out if 'INSERT INTO app.consent (' in line]))
        rec = u(org, 103)
        out.append(f"INSERT INTO app.consent (id, org_id, member_id, brand_id, channel, purpose, status, source, evidence, recorded_by, granted_at) VALUES ({q(cid)}, {q(u(org,1))}, {q(u(org,n+100))}, {q(u(org,3))}, {q(ch)}, {q(purpose)}, 'granted', 'front_desk', 'Demo: formulario de inscripción v1', {q(rec)}, now());")
        out.append(f"INSERT INTO app.consent_event (org_id, consent_id, member_id, brand_id, channel, purpose, status, source, evidence, recorded_by) VALUES ({q(u(org,1))}, {q(cid)}, {q(u(org,n+100))}, {q(u(org,3))}, {q(ch)}, {q(purpose)}, 'granted', 'front_desk', 'Demo: formulario de inscripción v1', {q(rec)});")
    for ln, ch, frm, body in INBOUND[org]:
        out.append(f"INSERT INTO app.inbound_message (org_id, brand_id, location_id, channel, from_address, body) VALUES ({q(u(org,1))}, {q(u(org,3))}, {q(u(org,ln))}, {q(ch)}, {q(frm)}, {q(body)});")
g, ward = GUARDIAN
out.append(f"INSERT INTO app.person (id, email) VALUES ({q(u(A,g))}, 'tutor.{g}.a@demo.invalid');")
out.append(f"INSERT INTO app.guardian_link (org_id, guardian_person_id, member_id) VALUES ({q(u(A,1))}, {q(u(A,g))}, {q(u(A,ward+100))});")
out += [f"ALTER TABLE app.{t} FORCE ROW LEVEL SECURITY;" for t in tables]
out.append("END $seed$;")
Path(__file__).with_name("demo.sql").write_text("\n".join(out) + "\n", encoding="utf-8")
print("ok", len(out))
