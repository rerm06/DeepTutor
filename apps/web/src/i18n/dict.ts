export type Lang = "es" | "en";
export const DICTIONARIES: Record<Lang, Dictionary> = { es, en };

export type Params = Record<string, string | number>;

export function translate(lang: Lang, key: MessageKey, params?: Params): string {
  const template = DICTIONARIES[lang][key] ?? DICTIONARIES.es[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (m, name: string) =>
    name in params ? String(params[name]) : m,
  );
}

/** Looks up a dynamic key (e.g. `status.${value}`); unknown values fall back to `fallback`. */
export function hasKey(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(es, key);
}
