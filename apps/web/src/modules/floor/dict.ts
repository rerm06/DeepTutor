export type FloorKey = keyof typeof floorDict.es;

/** Module translator plus a helper for enum labels (`eq.*`, `pattern.*`, `status.*`, …). */
export function useFloorT() {
  const m = useModuleT(floorDict);
  return {
    ...m,
    label: (prefix: "eq" | "pattern" | "status" | "issue" | "issueStatus", value: string) => {
      const key = `${prefix}.${value}` as FloorKey;
      return key in floorDict.es ? m.t(key) : value;
    },
  };
}
